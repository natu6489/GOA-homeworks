number = int(input("შეიტანეთ რიცხვი: "))

product = 1  # ნამრავლი

# ვამრავლებთ ყველა რიცხვს 1-დან number-ის ჩათვლით
for i in range(1, number + 1):
    product *= i

print("ფაქტორიალი არის:", product)









"""
% ნიშნული (მოდულო გაყოფა) — აბრუნებს გაყოფის ნაშთს.

მაგალითად:
7 % 3 = 1  (რადგან 7 იყოფა 3-ზე და ნაშთი რჩება 1)

სად გამოიყენება % ?

1) კენტ/ლუწი რიცხვების დასადგენად:
   თუ number % 2 == 0 → ლუწია
   თუ number % 2 == 1 → კენტია

2) გამყოფების პოვნისას:
   თუ number % divisor == 0 → რიცხვი უნაშთოდ იყოფა divisor-ზე

3) ციკლების შაბლონებში:
   მაგალითად, ყოველ მესამე ელემენტზე რაიმეს გაკეთება.
"""

# მაგალითები:
print(10 % 3)  # 1
print(20 % 5)  # 0
print(17 % 2)  # 1 → კენტია
print(100 % 10)  # 0










